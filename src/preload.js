'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('phosphor', {
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch (_) { return ''; } },
  describeFiles: (paths) => ipcRenderer.invoke('files:describe', paths),
  openDialog: (kind) => ipcRenderer.invoke('files:open-dialog', kind),
  savePlaylist: (items, name) => ipcRenderer.invoke('playlist:save', items, name),
  quickSaveAll: (tabs) => ipcRenderer.invoke('playlist:quicksave-all', tabs),
  quickSave: (items, name) => ipcRenderer.invoke('playlist:quicksave', items, name),
  plList: () => ipcRenderer.invoke('pl:list'),
  plOpen: (p) => ipcRenderer.invoke('pl:open', p),
  plDelete: (paths) => ipcRenderer.invoke('pl:delete', paths),
  loadPlaylist: () => ipcRenderer.invoke('playlist:load'),
  dlInfo: () => ipcRenderer.invoke('dl:info'),
  dlStart: (job) => ipcRenderer.invoke('dl:start', job),
  dlCancel: (id) => ipcRenderer.send('dl:cancel', id),
  dlChooseDir: (kind) => ipcRenderer.invoke('dl:choose-dir', kind),
  dlResetDirs: () => ipcRenderer.invoke('dl:reset-dirs'),
  dlOpenDir: (kind) => ipcRenderer.send('dl:open-dir', kind),
  onDl: (cb) => ipcRenderer.on('dl:event', (_e, ev) => cb(ev)),
  dlLookup: (vids) => ipcRenderer.invoke('dl:lookup', vids),
  dlRemember: (vid, kind, file, title) => ipcRenderer.send('dl:remember', vid, kind, file, title),
  dlmList: () => ipcRenderer.invoke('dlm:list'),
  dlmDelete: (rows) => ipcRenderer.invoke('dlm:delete', rows),
  dlmCleanMissing: () => ipcRenderer.invoke('dlm:clean-missing'),
  dlForget: (vid, kind) => ipcRenderer.send('dl:forget', vid, kind),
  filesExist: (paths) => ipcRenderer.invoke('files:exists', paths),
  trashFile: (p) => ipcRenderer.invoke('file:trash', p),
  listSubs: (file) => ipcRenderer.invoke('subs:list', file),
  openSubDialog: (near) => ipcRenderer.invoke('subs:open-dialog', near),
  onMediaKey: (cb) => ipcRenderer.on('media-key', (_e, a) => cb(a)),
  prepare: (file, opts) => ipcRenderer.invoke('media:prepare', file, opts),
  loadState: () => ipcRenderer.invoke('state:load'),
  saveState: (s) => ipcRenderer.send('state:save', s),
  webMeta: (url) => ipcRenderer.invoke('web:meta', url),
  openExternal: (url) => ipcRenderer.send('shell:open', url),
  showInFolder: (p) => ipcRenderer.send('shell:show', p),
  minimize: () => ipcRenderer.send('win:minimize'),
  close: () => ipcRenderer.send('win:close'),
  setFullscreen: (on) => ipcRenderer.invoke('win:fullscreen', on),
  setMini: (on) => ipcRenderer.invoke('win:mini', on),
  // movable windows (renderer/winmgr.js <-> windows.js)
  wmSync: (list, reflow) => ipcRenderer.send('wm:sync', list, reflow),
  wmDrag: (phase, id, mode) => ipcRenderer.send('wm:drag', phase, id, mode),
  wmPreset: (name) => ipcRenderer.invoke('wm:preset', name),
  wmOption: (key, value) => ipcRenderer.invoke('wm:option', key, value),
  wmInfo: () => ipcRenderer.invoke('wm:info'),
  wmPopup: (o) => ipcRenderer.send('wm:popup', o),
  wmPopupSize: (o) => ipcRenderer.send('wm:popup-size', o),
  wmPopupHide: () => ipcRenderer.send('wm:popup-hide'),
  wmDialog: (o) => ipcRenderer.send('wm:dialog', o),
  wmDialogHide: () => ipcRenderer.send('wm:dialog-hide'),
  wmDialogDrag: (phase) => ipcRenderer.send('wm:dialog-drag', phase),
  onWm: (cb) => { for (const ch of ['wm:snap', 'wm:layout', 'wm:closed', 'wm:popup-blur']) ipcRenderer.on(ch, (_e, v) => cb(ch, v)); },
  info: () => ipcRenderer.invoke('app:info'),
  updGet: () => ipcRenderer.invoke('upd:get'),
  updCheck: () => ipcRenderer.invoke('upd:check'),
  updMode: (mode) => ipcRenderer.invoke('upd:mode', mode),
  updDownload: (installAfter) => ipcRenderer.send('upd:download', installAfter),
  updCancel: () => ipcRenderer.send('upd:cancel'),
  updInstall: () => ipcRenderer.send('upd:install'),
  updSkip: () => ipcRenderer.send('upd:skip'),
  updDismiss: () => ipcRenderer.send('upd:dismiss'),
  updPage: () => ipcRenderer.send('upd:page'),
  onUpd: (cb) => ipcRenderer.on('upd:event', (_e, st) => cb(st)),
  onFullscreen: (cb) => ipcRenderer.on('fullscreen', (_e, v) => cb(v)),
  onOpenFiles: (cb) => ipcRenderer.on('open-files', (_e, v) => cb(v))
});
