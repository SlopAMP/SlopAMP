#!/usr/bin/env python3
"""Write the NSIS uninstall commands for exactly the files SlopAMP installs.

Usage: make_uninstall_list.py <staged app folder> <output .nsh>
Every staged file gets a Delete; every folder a plain RMDir (deepest first), which
only removes it once it's empty. So files that aren't SlopAMP's survive an uninstall,
even inside folders with the same names as ours.
"""
import os, sys

stage, out = sys.argv[1], sys.argv[2]
files, dirs = [], []
for root, dnames, fnames in os.walk(stage):
    rel = os.path.relpath(root, stage)
    for n in fnames:
        files.append(os.path.normpath(os.path.join(rel, n)))
    for n in dnames:
        dirs.append(os.path.normpath(os.path.join(rel, n)))
bad = [p for p in files + dirs if any(c in p for c in '"$`\r\n')]
if bad:
    sys.exit(f"make_uninstall_list: can't write these names into NSIS: {bad[:5]}")
win = lambda p: p.replace('/', '\\')
with open(out, 'w', encoding='utf-8') as f:
    f.write('; generated by build/make_uninstall_list.py, do not edit\n')
    for p in sorted(files):
        f.write(f'  Delete "$INSTDIR\\{win(p)}"\n')
    for p in sorted(dirs, key=lambda d: d.count(os.sep), reverse=True):
        f.write(f'  RMDir "$INSTDIR\\{win(p)}"\n')
print(f'uninstall list: {len(files)} files, {len(dirs)} folders')
