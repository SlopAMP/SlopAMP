"""Writes the built-in skins (src/renderer/skins/*.css) from the Classic skin.

Every skin is "Classic with changes": a colour transform applied to Classic's values (hue for the
colour skins, a whole new palette for the style skins) plus hand-picked values and a few extra CSS
rules. Run it after changing skins/classic.css or a skin below:  python3 build/skins/make_skins.py
The generated files are plain CSS and are committed, so the app needs nothing from here at runtime.
"""
import colorsys, os, re

