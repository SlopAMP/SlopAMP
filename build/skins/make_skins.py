def write(skin_id, name, desc, vars_, css=''):
    # Every skin names its dialog warning colour, even when it's Classic's (the skin's own amber, or Classic's),
    # so a warning never depends on what classic.css happens to say.
    vars_ = dict(vars_)
    vars_.setdefault('--warn-ink', vars_.get('--amber', VARS['--warn-ink']))
    lines = [f'/* SlopAMP skin: "{name}" — {desc}',
             '   Loaded on top of classic.css; only what differs from Classic is here.',
             '   Generated by build/skins/make_skins.py (edit there, then run it). */',
             ':root {'] + [f'  {k}: {v};' for k, v in vars_.items()] + ['}']
    if css.strip(): lines += ['', css.strip()]
    open(os.path.join(DIR, f'{skin_id}.css'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')

