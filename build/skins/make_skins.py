DIR = os.path.join(ROOT, 'src', 'renderer', 'skins')
classic = open(os.path.join(DIR, 'classic.css'), encoding='utf-8').read()
VARS = dict(re.findall(r'^\s*(--[\w-]+):\s*([^;]+);', classic[classic.index(':root {'):], flags=re.M))
COL = re.compile(r'#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)')

def parse(c):
    if c.startswith('#'):
        h = c[1:]
        if len(h) == 3: h = ''.join(x * 2 for x in h)
        return int(h[0:2], 16) / 255, int(h[2:4], 16) / 255, int(h[4:6], 16) / 255, None
    n = re.findall(r'[\d.]+', c)
    return int(n[0]) / 255, int(n[1]) / 255, int(n[2]) / 255, (float(n[3]) if len(n) > 3 else None)

def fmt(r, g, b, a=None):
    r, g, b = (max(0.0, min(1.0, x)) for x in (r, g, b))
    if a is None: return '#%02x%02x%02x' % (round(r * 255), round(g * 255), round(b * 255))
    return 'rgba(%d,%d,%d,%s)' % (round(r * 255), round(g * 255), round(b * 255), ('%g' % a).lstrip('0') if a < 1 else '1')

def transform(fn, skip=()):
    out = {}
    for k, v in VARS.items():
        if k in skip: continue
        nv = COL.sub(lambda m: fmt(*fn(*parse(m.group(0)))), v)
        same = COL.sub(lambda m: fmt(*parse(m.group(0))), v)
        if nv != same: out[k] = nv
    return out

def hls(r, g, b): h, l, s = colorsys.rgb_to_hls(r, g, b); return h * 360, l, s
def chroma(r, g, b): return max(r, g, b) - min(r, g, b)
def is_green(r, g, b): h, l, s = hls(r, g, b); return 70 <= h < 175 and chroma(r, g, b) > 0.02
def is_amber(r, g, b): h, l, s = hls(r, g, b); return 35 <= h < 70 and chroma(r, g, b) > 0.05

def recolor(hue, lift=0.0, amber_to=None):
    """Turn Classic's greens into `hue` (degrees); `lift` brightens them (blue/purple read darker)."""
    def f(r, g, b, a):
        if is_green(r, g, b):
            h, l, s = colorsys.rgb_to_hls(r, g, b)
            r, g, b = colorsys.hls_to_rgb((hue / 360) % 1, min(1, l + lift * l), s)
        elif amber_to is not None and is_amber(r, g, b):
            h, l, s = colorsys.rgb_to_hls(r, g, b)
            r, g, b = colorsys.hls_to_rgb((amber_to / 360) % 1, l, s)
        return r, g, b, a
    return f

def neutrals(fnL, hue=None, sat=None):
    """Remap Classic's greys/near-blacks: new lightness fnL(l), optionally tinted."""
    def f(r, g, b, a):
        if chroma(r, g, b) > 0.12: return r, g, b, a
        h, l, s = colorsys.rgb_to_hls(r, g, b)
        if hue is not None: h, s = hue / 360, sat
        r, g, b = colorsys.hls_to_rgb(h, max(0, min(1, fnL(l))), s)
        return r, g, b, a
    return f

def chain(*fns):
    def f(r, g, b, a):
        for fn in fns: r, g, b, a = fn(r, g, b, a)
        return r, g, b, a
    return f

